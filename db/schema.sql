CREATE TABLE CS_USERS (
  USER_ID        NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  EMAIL          VARCHAR2(255) NOT NULL,
  PASSWORD_HASH  VARCHAR2(500) NOT NULL,
  ROLE           VARCHAR2(20) NOT NULL CHECK (ROLE IN ('STUDENT','RECRUITER','ADMIN')),
  ACCOUNT_STATUS VARCHAR2(20) DEFAULT 'ACTIVE' NOT NULL,
  EMAIL_VERIFIED NUMBER(1) DEFAULT 0 NOT NULL,
  CREATED_AT     TIMESTAMP DEFAULT SYSTIMESTAMP
);
CREATE UNIQUE INDEX UX_CS_USERS_EMAIL ON CS_USERS (LOWER(EMAIL));

CREATE TABLE CS_SESSIONS (
  SESSION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  USER_ID    NUMBER NOT NULL REFERENCES CS_USERS(USER_ID),
  TOKEN_HASH VARCHAR2(64) NOT NULL UNIQUE,
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
  EXPIRES_AT TIMESTAMP NOT NULL,
  REVOKED_AT TIMESTAMP
);

CREATE TABLE CS_STUDENTS (
  STUDENT_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  USER_ID    NUMBER UNIQUE REFERENCES CS_USERS(USER_ID),
  FULL_NAME  VARCHAR2(150) NOT NULL,
  EMAIL      VARCHAR2(255) NOT NULL UNIQUE,
  BRANCH     VARCHAR2(100),
  GRADUATION_YEAR NUMBER(4),
  CGPA NUMBER(4,2), SSC_MARKS NUMBER(5,2), HSC_MARKS NUMBER(5,2),
  INTERNSHIPS NUMBER DEFAULT 0, PROJECTS NUMBER DEFAULT 0,
  WORKSHOPS_CERTIFICATIONS NUMBER DEFAULT 0,
  APTITUDE_TEST_SCORE NUMBER(5,2), SOFT_SKILLS_RATING NUMBER(3,1),
  EXTRACURRICULAR_ACTIVITIES VARCHAR2(3) CHECK (EXTRACURRICULAR_ACTIVITIES IN ('Yes','No')),
  PLACEMENT_TRAINING VARCHAR2(3) CHECK (PLACEMENT_TRAINING IN ('Yes','No'))
);

CREATE TABLE CS_COMPANIES (
  COMPANY_ID   NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  USER_ID      NUMBER UNIQUE REFERENCES CS_USERS(USER_ID),
  COMPANY_NAME VARCHAR2(200) NOT NULL,
  EMAIL        VARCHAR2(255) NOT NULL UNIQUE,
  INDUSTRY     VARCHAR2(100),
  LOCATION     VARCHAR2(200)
);

CREATE TABLE CS_JOBS (
  JOB_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  COMPANY_ID NUMBER NOT NULL REFERENCES CS_COMPANIES(COMPANY_ID),
  JOB_TITLE VARCHAR2(150) NOT NULL,
  JOB_DESCRIPTION CLOB,
  JOB_TYPE VARCHAR2(30),
  MIN_CGPA NUMBER(4,2),
  MAX_BACKLOGS NUMBER DEFAULT 0,
  SALARY_LPA NUMBER(6,2),
  LOCATION VARCHAR2(150),
  GRADUATION_YEAR NUMBER(4),
  DEADLINE DATE,
  JOB_STATUS VARCHAR2(10) DEFAULT 'OPEN' CHECK (JOB_STATUS IN ('DRAFT','OPEN','CLOSED')),
  POSTED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);

CREATE TABLE CS_SKILLS (
  SKILL_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  SKILL_NAME VARCHAR2(80) NOT NULL UNIQUE
);

CREATE TABLE CS_STUDENT_SKILLS (
  STUDENT_ID NUMBER NOT NULL REFERENCES CS_STUDENTS(STUDENT_ID),
  SKILL_ID   NUMBER NOT NULL REFERENCES CS_SKILLS(SKILL_ID),
  PROFICIENCY NUMBER(3) NOT NULL,
  PRIMARY KEY (STUDENT_ID, SKILL_ID)
);

CREATE TABLE CS_JOB_SKILLS (
  JOB_ID   NUMBER NOT NULL REFERENCES CS_JOBS(JOB_ID),
  SKILL_ID NUMBER NOT NULL REFERENCES CS_SKILLS(SKILL_ID),
  REQUIRED_LEVEL NUMBER(3) NOT NULL,
  IMPORTANCE     NUMBER(3) NOT NULL,
  PRIMARY KEY (JOB_ID, SKILL_ID)
);

CREATE TABLE CS_APPLICATIONS (
  APPLICATION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  STUDENT_ID NUMBER NOT NULL REFERENCES CS_STUDENTS(STUDENT_ID),
  JOB_ID     NUMBER NOT NULL REFERENCES CS_JOBS(JOB_ID),
  APPLIED_AT TIMESTAMP DEFAULT SYSTIMESTAMP,
  APPLICATION_STATUS VARCHAR2(20) DEFAULT 'APPLIED',
  MATCH_SCORE NUMBER(5,2),
  CONSTRAINT UQ_APPLICATION UNIQUE (STUDENT_ID, JOB_ID)
);

CREATE TABLE CS_PREDICTIONS (
  PREDICTION_ID NUMBER GENERATED ALWAYS AS IDENTITY PRIMARY KEY,
  STUDENT_ID NUMBER NOT NULL REFERENCES CS_STUDENTS(STUDENT_ID),
  PLACEMENT_PROBABILITY NUMBER(8,6),
  MODEL_VERSION VARCHAR2(20),
  CREATED_AT TIMESTAMP DEFAULT SYSTIMESTAMP
);